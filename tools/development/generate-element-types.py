"""Generate the public built-in Fleck type catalog from fleckc --schema.

The native parser's property contract is the source of truth for built-in tags.
Custom properties are declared in application code, never in this generator.
"""
import argparse
import json
import os
from pathlib import Path

parser = argparse.ArgumentParser()
parser.add_argument("schema", type=Path)
parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[2] / "bindings/csharp/Elements.cs")
parser.add_argument("--native-output", type=Path, default=Path(__file__).resolve().parents[2] / "include/sunfleck")
parser.add_argument("--catalog-output", type=Path, default=Path(__file__).resolve().parents[2] / "bindings/types")
args = parser.parse_args()
schema = json.loads(args.schema.read_text(encoding="utf-8"))
repository = Path(__file__).resolve().parents[2]
component_files = {'c': repository/'include/sunfleck/component_attributes.h',
                   'cpp': repository/'include/sunfleck/components.hpp',
                   'csharp': repository/'bindings/csharp/Components.cs'}
component_attributes = {}
for language, file in component_files.items():
    source_lines = file.read_text(encoding='utf-8').splitlines()
    component_attributes[language] = []
    for name, declaring in [('DataContext','FrameworkElement'), ('Template','Control')]:
        matches = [i+1 for i,line in enumerate(source_lines) if (name+'Property' in line and '=' in line) or name+'Property{' in line]
        assert len(matches)==1, (file, name, matches)
        component_attributes[language].append(dict(name=name,source=Path(os.path.relpath(file,args.catalog_output)).as_posix(),line=matches[0],
                                                   declaringType=({'c': 'ui_framework_element' if declaring == 'FrameworkElement' else 'ui_control',
                                                                  'cpp': 'sunfleck::'+declaring,
                                                                  'csharp': 'Sunfleck.'+declaring}[language])))

# Only hoist attributes whose complete schema contract is identical for every
# descendant. Document/theme declarations do not inherit visual-only attributes.
common_names = ("Style", "DataContext", "Id", "IsEnabled", "Visibility", "LayoutTransform", "RenderTransform", "RenderTransformOrigin", "Opacity", "IsFocusScope", "TabIndex", "IsTabStop", "ClipToBounds", "IsHitTestVisible", "FontFamily", "FontSize", "FontWeight", "FontStyle", "FontStretch", "Foreground", "TextAlignment", "TextWrapping", "TextTrimming", "LineHeight", "TextDecorations", "FlowDirection", "Height", "Width", "MinWidth", "MaxWidth", "MinHeight", "MaxHeight", "Margin", "HorizontalAlignment", "VerticalAlignment", "Weight", "Dock", "Grid.Row", "Grid.Column", "Grid.RowSpan", "Grid.ColumnSpan", "Panel.ZIndex", "Canvas.Left", "Canvas.Top")
layout_names = ("Spacing", "Padding")
shared = {name: next(a for a in schema["elements"][0]["attributes"] if a["name"] == name)
          for name in common_names + layout_names}
for element in schema["elements"]:
    attrs = {a["name"]: a for a in element["attributes"]}
    for name in common_names:
        assert attrs.get(name) == shared[name], (element["name"], name)
    if any(name in attrs for name in layout_names):
        for name in layout_names:
            assert attrs.get(name) == shared[name], (element["name"], name)

def parent(group, element):
    if group: return None
    return "LayoutElement" if any(a["name"] == "Padding" for a in element["attributes"]) else "VisualElement"

def owner(group, attr, cls):
    if not group and attr in common_names: return "VisualElement"
    if not group and attr in layout_names: return "LayoutElement"
    return cls

lines = ["// Generated by tools/development/generate-element-types.py from fleckc --schema.",
         "// Checked into source so F12 works before building an application.",
         "#nullable enable", "namespace Sunfleck.Elements;", ""]
cs_locations = {}
def cs_property(attribute, declaring):
    attr = attribute["name"]; kind = attribute["type"]
    cs = {"integer":"int", "length":"Length", "point":"Point", "matrix":"Matrix", "number":"double", "bool":"bool", "command":"Command?", "model":"PropertyModel?", "color":"Color", "thickness":"Thickness", "cornerRadius":"CornerRadius", "visibility":"Visibility", "fontWeight":"FontWeight", "fontStyle":"FontStyle", "fontStretch":"FontStretch", "flowDirection":"FlowDirection", "textDecorations":"TextDecorations", "textTrimming":"TextTrimming", "textWrapping":"TextWrapping", "textAlignment":"TextAlignment"}.get(kind,"string")
    bind = attribute.get("binding", False); mode = attribute.get("defaultMode", "OneWay")
    target = "PropertyTarget." + attr if bind else "null"
    cs_locations[(declaring, attr)] = len(lines) + 1
    modifier = "new " if attr == "DataContext" and declaring == "VisualElement" else ""
    lines.append(f'    public {modifier}static readonly ElementProperty<{cs}> {attr.replace(".", "")}Property = new("{attr}", {target}, PropertyBindingMode.{mode});')
    if bind and attr in ("Height", "Width", "MinWidth", "MaxWidth", "MinHeight", "MaxHeight", "Margin", "HorizontalAlignment", "VerticalAlignment"):
        return
    if bind and attr != "Command":
        lines.append(f"    public {cs} {attr} {{ get => GetValue({attr}Property); set => SetValue({attr}Property, value); }}")
    elif bind:
        lines.append("    public void SetCommand(Command? command) => SetValue(CommandProperty, command);")

for cls, base, names in [("VisualElement", "global::Sunfleck.FrameworkElement", common_names),
                         ("LayoutElement", "VisualElement", layout_names)]:
    lines += [f"public abstract class {cls} : {base}", "{", f"    protected {cls}(Node node) : base(node) {{ }}"]
    for name in names: cs_property(shared[name], cls)
    lines += ["}", ""]

catalog = []
legacy_elements = schema.get("legacyElements", [])
visual_elements = sorted(schema["elements"] + legacy_elements, key=lambda element: element["kind"])
legacy_names = {element["name"] for element in legacy_elements}
groups = [("", visual_elements), ("Document", schema["documents"]), ("Theme", schema["templateElements"]["elements"])]
for group, definitions in groups:
    for element in definitions:
        name = element["name"]; class_name = group + name
        base = parent(group, element) or "global::Sunfleck.FrameworkElement"
        class_line = len(lines) + 1
        lines += [f"public sealed class {class_name} : {base}", "{"]
        if not group:
            lines += [f"    public {class_name}(Node node) : base(node) {{ }}",
                      f"    public {class_name}(App app) : base(app.CreateNode(NodeKind.{name})) {{ }}"]
        props = []
        for attribute in element["attributes"]:
            attr = attribute["name"]; declaring = owner(group, attr, class_name)
            if declaring == class_name: cs_property(attribute, declaring)
            props.append((attr, attribute["type"], attribute.get("binding",False), attribute.get("twoWay",False),
                          attribute.get("defaultMode","OneWay"), cs_locations[(declaring, attr)]))
        lines += ["}", ""]
        if group or name not in legacy_names:
            catalog.append((group,name,class_name,class_line,props))
lines += ["/// <summary>Code declaration locations for the shared language service. No element instances are constructed.</summary>",
          "public static class BuiltInElementTypes", "{",
          "    public sealed record Property(string Name, string Kind, bool Bindable, bool TwoWay, string Mode, int Line);",
          "    public sealed record Element(string Group, string Name, Type Type, int Line, Property[] Properties);",
          "    public static string SourceFile { get; } = Source();",
          "    private static string Source([System.Runtime.CompilerServices.CallerFilePath] string file = \"\") => file;",
          "    public static IReadOnlyList<Element> All { get; } = new Element[]", "    {"]
for group,name,cls,line,props in catalog:
    lines += [f'        new("{group}", "{name}", typeof({cls}), {line}, new Property[] {{']
    for attr,kind,bind,two,mode,pline in props:
        lines += [f'            new("{attr}", "{kind}", {str(bind).lower()}, {str(two).lower()}, "{mode}", {pline}),']
    lines += ["        }),"]
lines += ["    };", "    public sealed record ComponentAttribute(string Name, string File, int Line);",
          "    public static IReadOnlyList<ComponentAttribute> ComponentAttributes { get; } = new ComponentAttribute[]", "    {"]
for attribute in component_attributes['csharp']:
    lines.append(f'        new("{attribute["name"]}", "Components.cs", {attribute["line"]}),')
lines += ["    };", "}", ""]
args.output.write_bytes("\n".join(lines).encode("utf-8"))

# Public native declarations and navigation maps come from the same schema.
# Non-bindable Fleck attributes remain descriptors, not invented runtime setters.
args.native_output.mkdir(parents=True, exist_ok=True)
args.catalog_output.mkdir(parents=True, exist_ok=True)
c = ['// Generated from fleckc --schema. Do not edit.', '#pragma once',
     '#include <sunfleck/component_attributes.h>', '',
     'typedef struct ui_element_property {',
     '    const char *name, *schema_type;',
     '    ui_value_kind kind;',
     '    uint32_t bindable, two_way;',
     '    ui_property target;',
     '    ui_binding_mode mode;',
     '} ui_element_property;', '',
     'static inline ui_result ui_element_bind(ui_node *node, const ui_element_property *property,',
     '    ui_model *model, const char *path, ui_binding_mode mode) {',
     '    if (!property || !property->bindable) { return UI_ERROR_INVALID_ARGUMENT; }',
     '    ui_binding_options options = {sizeof(options), 1, property->target, path,',
     '        mode == UI_BIND_DEFAULT ? property->mode : mode, UI_UPDATE_PROPERTY_CHANGED, ""};',
     '    return ui_node_bind_property(node, model, &options);', '}', '']
cpp = ['// Generated from fleckc --schema. Do not edit.', '#pragma once',
       '#include <sunfleck/components.hpp>', '', 'namespace sunfleck::elements {',
       'template<class T> struct ElementProperty {',
       '    using value_type = T;',
       '    const char *name, *schema_type;',
       '    bool bindable, two_way;',
       '    ui_property target;',
       '    ui_binding_mode mode;', '};', '',
       'class Element : public sunfleck::FrameworkElement {', 'public:',
       '    explicit Element(Node node) : FrameworkElement(node, nullptr) {}',
       '    template<class T> void bind(const ElementProperty<T>& property, PropertyModel& model,',
       '        const char *path, ui_binding_mode mode = UI_BIND_DEFAULT) {',
       '        if (!property.bindable) { throw Error(UI_ERROR_INVALID_ARGUMENT); }',
       '        model.bind(node(), property.target, path, mode == UI_BIND_DEFAULT ? property.mode : mode);',
       '    }', '};', '']
c_locations = {}; cpp_locations = {}
def native_property(attr, declaring):
    prop = attr['name']; kind = attr['type']; bind = attr.get('binding',False); two = attr.get('twoWay',False)
    mode = {'OneWay':'UI_BIND_ONE_WAY','OneTime':'UI_BIND_ONE_TIME','TwoWay':'UI_BIND_TWO_WAY'}[attr.get('defaultMode','OneWay')]
    target = {'Text':'UI_PROPERTY_TEXT','Content':'UI_PROPERTY_CONTENT','IsEnabled':'UI_PROPERTY_IS_ENABLED','Value':'UI_PROPERTY_VALUE','Command':'UI_PROPERTY_COMMAND','Height':'UI_PROPERTY_HEIGHT','Width':'UI_PROPERTY_WIDTH','MinWidth':'UI_PROPERTY_MIN_WIDTH','MaxWidth':'UI_PROPERTY_MAX_WIDTH','MinHeight':'UI_PROPERTY_MIN_HEIGHT','MaxHeight':'UI_PROPERTY_MAX_HEIGHT','Margin':'UI_PROPERTY_MARGIN','HorizontalAlignment':'UI_PROPERTY_HORIZONTAL_ALIGNMENT','VerticalAlignment':'UI_PROPERTY_VERTICAL_ALIGNMENT','Spacing':'UI_PROPERTY_SPACING','Padding':'UI_PROPERTY_PADDING','Weight':'UI_PROPERTY_WEIGHT','Source':'UI_PROPERTY_SOURCE','ItemsSource':'UI_PROPERTY_ITEMS_SOURCE','DataContext':'UI_PROPERTY_DATA_CONTEXT','Background':'UI_PROPERTY_BACKGROUND','BorderBrush':'UI_PROPERTY_BORDER_BRUSH','BorderThickness':'UI_PROPERTY_BORDER_THICKNESS','CornerRadius':'UI_PROPERTY_CORNER_RADIUS','Visibility':'UI_PROPERTY_VISIBILITY','LayoutTransform':'UI_PROPERTY_LAYOUT_TRANSFORM','RenderTransform':'UI_PROPERTY_RENDER_TRANSFORM','RenderTransformOrigin':'UI_PROPERTY_RENDER_TRANSFORM_ORIGIN','Opacity':'UI_PROPERTY_OPACITY','IsFocusScope':'UI_PROPERTY_IS_FOCUS_SCOPE','TabIndex':'UI_PROPERTY_TAB_INDEX','IsTabStop':'UI_PROPERTY_IS_TAB_STOP','ClipToBounds':'UI_PROPERTY_CLIP_TO_BOUNDS','IsHitTestVisible':'UI_PROPERTY_IS_HIT_TEST_VISIBLE','FontFamily':'UI_PROPERTY_FONT_FAMILY','FontSize':'UI_PROPERTY_FONT_SIZE','FontWeight':'UI_PROPERTY_FONT_WEIGHT','FontStyle':'UI_PROPERTY_FONT_STYLE','FontStretch':'UI_PROPERTY_FONT_STRETCH','Foreground':'UI_PROPERTY_FOREGROUND','TextAlignment':'UI_PROPERTY_TEXT_ALIGNMENT','TextWrapping':'UI_PROPERTY_TEXT_WRAPPING','TextTrimming':'UI_PROPERTY_TEXT_TRIMMING','LineHeight':'UI_PROPERTY_LINE_HEIGHT','TextDecorations':'UI_PROPERTY_TEXT_DECORATIONS','FlowDirection':'UI_PROPERTY_FLOW_DIRECTION'}[prop] if bind else 'UI_PROPERTY_TEXT'
    value = {'integer':'UI_VALUE_INT','length':'UI_VALUE_LENGTH','matrix':'UI_VALUE_MATRIX','point':'UI_VALUE_POINT','number':'UI_VALUE_DOUBLE','bool':'UI_VALUE_BOOL','command':'UI_VALUE_COMMAND','model':'UI_VALUE_MODEL','color':'UI_VALUE_COLOR','thickness':'UI_VALUE_THICKNESS','cornerRadius':'UI_VALUE_CORNER_RADIUS','visibility':'UI_VALUE_ENUM','fontWeight':'UI_VALUE_ENUM','fontStyle':'UI_VALUE_ENUM','fontStretch':'UI_VALUE_ENUM','flowDirection':'UI_VALUE_ENUM','textDecorations':'UI_VALUE_ENUM','textTrimming':'UI_VALUE_ENUM','textWrapping':'UI_VALUE_ENUM','textAlignment':'UI_VALUE_ENUM'}.get(kind,'UI_VALUE_STRING')
    native = {'integer':'int','length':'ui_length','matrix':'ui_matrix','point':'ui_point','number':'double','bool':'bool','command':'ui_command *','model':'ui_model *','color':'ui_color','thickness':'ui_thickness','cornerRadius':'ui_corner_radius','visibility':'ui_visibility','fontWeight':'ui_font_weight','fontStyle':'ui_font_style','fontStretch':'ui_font_stretch','flowDirection':'ui_flow_direction','textDecorations':'ui_text_decorations','textTrimming':'ui_text_trimming','textWrapping':'ui_text_wrapping','textAlignment':'ui_text_alignment'}.get(kind,'std::string')
    c_locations[(declaring,prop)] = len(c)+1; cpp_locations[(declaring,prop)] = len(cpp)+1
    c.append(f'static const ui_element_property ui_{declaring}_{prop.replace(".", "")}Property = {{"{prop}", "{kind}", {value}, {int(bind)}, {int(two)}, {target}, {mode}}};')
    cpp.append(f'    inline static constexpr ElementProperty<{native}> {prop.replace(".", "")}Property{{"{prop}", "{kind}", {str(bind).lower()}, {str(two).lower()}, {target}, {mode}}};')

for cls, base, names in [("VisualElement", "Element", common_names), ("LayoutElement", "VisualElement", layout_names)]:
    fields = 'ui_framework_element base; ui_node *node;' if cls == 'VisualElement' else 'ui_VisualElement base;'
    c += [f'typedef struct ui_{cls} {{ {fields} }} ui_{cls};']
    cpp += [f'class {cls} : public {base} {{', 'public:', f'    using {base}::{base};']
    for name in names: native_property(shared[name], cls)
    if cls == 'LayoutElement':
        c += [f'#define ui_LayoutElement_{name.replace(".", "")}Property ui_VisualElement_{name.replace(".", "")}Property' for name in common_names]
    c += ['']; cpp += ['};','']
maps = {'c': [], 'cpp': [], 'csharp': []}
for group, definitions in groups:
    for element in definitions:
        name = element['name']; cls = group + name; base = parent(group, element)
        c_name = 'ui_' + cls
        c_entry = dict(group=group, name=name, className=c_name, line=len(c)+1, properties=[])
        cpp_entry = dict(group=group, name=name, className='sunfleck::elements::'+cls, line=len(cpp)+1, properties=[])
        fields = f'ui_{base} base;' if base else 'ui_framework_element base; ui_node *node;'
        c += [f'typedef struct {c_name} {{ {fields} }} {c_name};']
        cpp_base = base or 'Element'
        cpp += [f'class {cls} : public {cpp_base} {{', 'public:', f'    using {cpp_base}::{cpp_base};']
        if not group:
            visual = 'base.base' if base == 'LayoutElement' else 'base'
            c += [f'static inline ui_node *{c_name}_node(const {c_name} *element) {{ return element ? element->{visual}.node : NULL; }}',
                  f'static inline ui_result {c_name}_create(ui_app *app, {c_name} *out) {{',
                  '    if (!out) { return UI_ERROR_INVALID_ARGUMENT; }',
                  f'    out->{visual}.base.component = NULL; out->{visual}.node = NULL;',
                  f'    return ui_node_create(app, (ui_node_kind){element["kind"]}, &out->{visual}.node);', '}']
            cpp += [f'    explicit {cls}(App& app) : {cpp_base}(app.createNode(static_cast<ui_node_kind>({element["kind"]}))) {{}}']
        for attr in element['attributes']:
            prop = attr['name']; declaring = owner(group, prop, cls)
            if declaring == cls: native_property(attr, declaring)
            else: c += [f'#define {c_name}_{prop.replace(".", "")}Property ui_{declaring}_{prop.replace(".", "")}Property']
            c_entry['properties'].append(dict(name=prop,line=c_locations[(declaring,prop)],declaringType='ui_'+declaring))
            cpp_entry['properties'].append(dict(name=prop,line=cpp_locations[(declaring,prop)],declaringType='sunfleck::elements::'+declaring))
        c += ['']; cpp += ['};','']
        if group or name not in legacy_names:
            maps['c'].append(c_entry); maps['cpp'].append(cpp_entry)
cpp += ['} // namespace sunfleck::elements', '']
for group,name,cls,line,props in catalog:
    maps['csharp'].append(dict(group=group,name=name,className='Sunfleck.Elements.'+cls,line=line,
                              properties=[dict(name=a,line=l,declaringType='Sunfleck.Elements.'+owner(group,a,cls)) for a,k,b,t,m,l in props]))
sources = {'c':args.native_output/'elements.h', 'cpp':args.native_output/'elements.hpp', 'csharp':args.output}
sources['c'].write_text('\n'.join(c),encoding='utf-8')
sources['cpp'].write_text('\n'.join(cpp),encoding='utf-8')
for lang, entries in maps.items():
    manifest = dict(version=1,language=lang,source=Path(os.path.relpath(sources[lang],args.catalog_output)).as_posix(),types=entries,componentAttributes=component_attributes[lang])
    (args.catalog_output/(lang+'.json')).write_text(json.dumps(manifest,indent=2)+'\n',encoding='utf-8')
