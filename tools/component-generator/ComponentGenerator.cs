using System.Text;
using System.Text.Json;
using System.Xml.Linq;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Sunfleck.Generators;

[Generator]
public sealed class ComponentGenerator : ISourceGenerator
{
    private static readonly DiagnosticDescriptor Invalid = new("FLK001", "Invalid Fleck component", "{0}", "Fleck", DiagnosticSeverity.Error, true);
    public void Initialize(GeneratorInitializationContext context) { }
    private static string Quote(string text) => SymbolDisplay.FormatLiteral(text, true);
    private static IEnumerable<INamedTypeSymbol> Hierarchy(INamedTypeSymbol type)
    {
        for (var current = type; current is not null; current = current.BaseType) { yield return current; }
    }
    public void Execute(GeneratorExecutionContext context)
    {
        string assembly = context.Compilation.AssemblyName ?? "Application";
        string registry = new(assembly.Select(c => char.IsLetterOrDigit(c) ? c : '_').ToArray());
        registry = "Fleck_" + registry;
        var code = new StringBuilder("// <auto-generated/>\n#nullable enable\n");
        code.Append("[assembly: global::Sunfleck.FleckRegistrationAttribute(typeof(global::Sunfleck.Generated.").Append(registry).Append("))]\n");
        code.Append("namespace Sunfleck.Generated { public static class ").Append(registry).Append(" { public static void Register(global::Sunfleck.App app) {\n");
        foreach (var reference in context.Compilation.References)
        {
            if (context.Compilation.GetAssemblyOrModuleSymbol(reference) is not IAssemblySymbol referenced) { continue; }
            foreach (var attribute in referenced.GetAttributes().Where(a => a.AttributeClass?.ToDisplayString() == "Sunfleck.FleckRegistrationAttribute"))
            {
                if (attribute.ConstructorArguments[0].Value is INamedTypeSymbol type) { code.Append(type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)).Append(".Register(app);\n"); }
            }
        }
        // Registration is per App and idempotent across diamond project references.
        code.Append("if (!app.BeginComponentLibrary(").Append(Quote(assembly)).Append(")) return;\n");
        var resources = new List<(string Path, string Text)>();
        foreach (var file in context.AdditionalFiles.Where(f => f.Path.EndsWith(".fleck", StringComparison.OrdinalIgnoreCase)))
        {
            try {
                var text = file.GetText(context.CancellationToken)?.ToString() ?? "";
                var document = XDocument.Parse(text);
                if (document.Root?.Name.LocalName is "UserControl" or "ControlTemplate") { resources.Add((file.Path, text)); }
            } catch (Exception error) { context.ReportDiagnostic(Diagnostic.Create(Invalid, Location.None, file.Path + ": " + error.Message)); }
        }
        if (resources.Count > 0) {
            code.Append("app.RegisterFleckResources(new global::System.Collections.Generic.KeyValuePair<string,string>[] {\n");
            foreach (var resource in resources) { code.Append("new(").Append(Quote(resource.Path)).Append(',').Append(Quote(resource.Text)).Append("),\n"); }
            code.Append("});\n");
        }
        var manifestTypes = new List<Dictionary<string, object?>>();
        var definitions = new List<Dictionary<string, object?>>();
        var componentDocuments = new Dictionary<string, (string Namespace, string Kind)>(StringComparer.Ordinal);
        context.AnalyzerConfigOptions.GlobalOptions.TryGetValue("build_property.CompilerGeneratedFilesOutputPath", out var generatedDirectory);
        foreach (var resource in resources) {
            var root = XDocument.Parse(resource.Text).Root!;
            string identity = root.Attribute("Class")?.Value ?? "";
            string ns = root.Attribute("Namespace")?.Value ?? "";
            if (identity.Length == 0 || ns.Length == 0 || identity.Split('.').Any(part => !SyntaxFacts.IsValidIdentifier(part))) {
                context.ReportDiagnostic(Diagnostic.Create(Invalid, Location.None, resource.Path + ": Class and Namespace must identify a valid code type.")); continue;
            }
            if (!componentDocuments.TryAdd(identity, (ns, root.Name.LocalName))) {
                context.ReportDiagnostic(Diagnostic.Create(Invalid, Location.None, "Duplicate Fleck Class: " + identity)); continue;
            }
            var existing = context.Compilation.GetTypeByMetadataName(identity);
            var source = existing?.Locations.FirstOrDefault(l => l.IsInSource)?.GetLineSpan();
            int split = identity.LastIndexOf('.');
            string shortName = identity[(split + 1)..];
            string hint = identity + ".g.cs";
            string generatedPath = Path.Combine(generatedDirectory ?? "obj/fleck-generated", "Sunfleck.ComponentGenerator", "Sunfleck.Generators.ComponentGenerator", hint);
            var sourceInfo = source is { } location ? (object)new { uri = location.Path, line = location.StartLinePosition.Line + 1, column = location.StartLinePosition.Character + 1 }
                : new { uri = Path.GetFullPath(generatedPath), line = 4, column = 1 };
            bool template = root.Name.LocalName == "ControlTemplate";
            if (existing is null) {
                string generatedType = "// <auto-generated/>\n#nullable enable\n" + (split < 0 ? "// Global namespace\n" : "namespace " + identity[..split] + ";\n") +
                    "public partial class " + shortName + " : global::Sunfleck." + (template ? "FrameworkElement" : "UserControl") + " { }\n";
                context.AddSource(hint, generatedType);
                if (!template) {
                    code.Append("app.RegisterComponent<global::").Append(identity).Append(">(").Append(Quote(ns)).Append(',').Append(Quote(shortName)).Append(");\n");
                    manifestTypes.Add(new() { ["namespace"] = ns, ["name"] = shortName, ["className"] = identity, ["baseType"] = "Sunfleck.UserControl", ["properties"] = Array.Empty<object>(), ["source"] = sourceInfo });
                }
            }
            if (template) { definitions.Add(new() { ["namespace"] = ns, ["name"] = shortName, ["className"] = identity, ["source"] = sourceInfo, ["template"] = true }); }
        }
        var seen = new HashSet<ISymbol>(SymbolEqualityComparer.Default);
        foreach (var tree in context.Compilation.SyntaxTrees)
        {
            var semantic = context.Compilation.GetSemanticModel(tree);
            foreach (var declaration in tree.GetRoot(context.CancellationToken).DescendantNodes().OfType<ClassDeclarationSyntax>())
            {
                if (semantic.GetDeclaredSymbol(declaration, context.CancellationToken) is not INamedTypeSymbol type || !seen.Add(type)) { continue; }
                var attribute = type.GetAttributes().FirstOrDefault(a => a.AttributeClass?.ToDisplayString() == "Sunfleck.FleckComponentAttribute");
                componentDocuments.TryGetValue(type.ToDisplayString(), out var documentType);
                if (attribute is null && documentType.Kind != "UserControl") { continue; }
                var ns = attribute?.ConstructorArguments[0].Value?.ToString() ?? documentType.Namespace ?? "";
                var name = attribute?.ConstructorArguments[1].Value?.ToString() ?? type.Name;
                void Error(string message) => context.ReportDiagnostic(Diagnostic.Create(Invalid, declaration.GetLocation(), message));
                if (!Hierarchy(type).Any(t => t.ToDisplayString() == "Sunfleck.FrameworkElement") || type.IsAbstract || type.IsGenericType ||
                    !type.InstanceConstructors.Any(c => c.Parameters.Length == 0 && c.DeclaredAccessibility == Accessibility.Public)) {
                    Error("A Fleck component must be a non-abstract FrameworkElement, UserControl or Control with a public parameterless constructor and no generic parameters.");
                    continue;
                }
                if (documentType.Kind == "UserControl" && ns != documentType.Namespace) {
                    Error("Fleck Namespace must match the code type's namespace URI."); continue;
                }
                if (name != type.Name || string.IsNullOrWhiteSpace(ns)) {
                    Error("Fleck component identity requires a namespace URI and the code type's short name.");
                    continue;
                }
                foreach (var resource in resources) {
                    var root = XDocument.Parse(resource.Text).Root!;
                    var identity = root.Attribute("Class")?.Value;
                    if (root.Name.LocalName == "UserControl" && root.Attribute("Namespace")?.Value == ns && identity?.Split('.').Last() == name && identity != type.ToDisplayString()) {
                        Error(resource.Path + ": Class must match the full code type name " + type.ToDisplayString());
                    }
                }
                string Named(string key) => attribute?.NamedArguments.FirstOrDefault(a => a.Key == key).Value.Value?.ToString() ?? "";
                var propertyMetadata = new List<Dictionary<string, object?>>();
                var eventMetadata = Hierarchy(type).SelectMany(t => t.GetAttributes()).Where(a => a.AttributeClass?.ToDisplayString() == "Sunfleck.FleckEventAttribute").Select(a => a.ConstructorArguments[0].Value!.ToString()!).Distinct().ToArray();
                var partAttributes = Hierarchy(type).SelectMany(t => t.GetAttributes()).Where(a => a.AttributeClass?.ToDisplayString() == "Sunfleck.FleckTemplatePartAttribute").GroupBy(a => a.ConstructorArguments[0].Value).Select(g => g.First()).ToArray();
                var partMetadata = new List<Dictionary<string, object?>>();
                foreach (var part in partAttributes) {
                    var kindValue = part.ConstructorArguments[1];
                    string? kind = ((INamedTypeSymbol)kindValue.Type!).GetMembers().OfType<IFieldSymbol>().FirstOrDefault(f => Equals(f.ConstantValue, kindValue.Value))?.Name;
                    if (kind is null) { Error("Unknown node kind in FleckTemplatePart."); continue; }
                    partMetadata.Add(new() { ["name"] = part.ConstructorArguments[0].Value, ["kind"] = kind, ["required"] = part.NamedArguments.FirstOrDefault(a => a.Key == "Required").Value.Value is false ? 0 : 1 });
                }
                var location = declaration.Identifier.GetLocation().GetLineSpan();
                manifestTypes.Add(new() { ["namespace"] = ns, ["name"] = name, ["className"] = type.ToDisplayString(), ["baseType"] = type.BaseType?.ToDisplayString(), ["templateNamespace"] = Named("TemplateNamespace").Length == 0 ? ns : Named("TemplateNamespace"), ["template"] = Named("Template"), ["properties"] = propertyMetadata, ["events"] = eventMetadata, ["parts"] = partMetadata, ["source"] = new { uri = location.Path, line = location.StartLinePosition.Line + 1, column = location.StartLinePosition.Character + 1 } });
                code.Append("app.RegisterComponent<").Append(type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)).Append(">(").Append(Quote(ns)).Append(',').Append(Quote(name)).Append(", new global::Sunfleck.ComponentProperty[] {\n");
                foreach (var property in Hierarchy(type).SelectMany(t => t.GetMembers().OfType<IPropertySymbol>()).GroupBy(p => p.Name).Select(g => g.First()))
                {
                    var metadata = property.GetAttributes().FirstOrDefault(a => a.AttributeClass?.ToDisplayString() == "Sunfleck.FleckPropertyAttribute");
                    if (metadata is null) { continue; }
                    if (property.IsStatic || property.IsIndexer || property.GetMethod?.DeclaredAccessibility != Accessibility.Public) {
                        Error("Fleck property " + property.Name + " must be a public instance property with a getter."); continue;
                    }
                    var defaultValue = metadata.NamedArguments.FirstOrDefault(a => a.Key == "Default").Value;
                    string literal = defaultValue.Value switch { null => "null", string text => Quote(text), bool value => value ? "true" : "false", _ => Convert.ToString(defaultValue.Value, System.Globalization.CultureInfo.InvariantCulture) ?? "null" };
                    bool readOnly = metadata.NamedArguments.FirstOrDefault(a => a.Key == "ReadOnly").Value.Value is true;
                    int mode = metadata.NamedArguments.FirstOrDefault(a => a.Key == "Mode").Value.Value is int m ? m : 0;
                    int effects = metadata.NamedArguments.FirstOrDefault(a => a.Key == "Effects").Value.Value is int flags ? flags : -1;
                    string referenceType = property.Type.WithNullableAnnotation(NullableAnnotation.NotAnnotated).ToDisplayString();
                    string propertyKind = property.Type.SpecialType switch {
                        SpecialType.System_String => "string", SpecialType.System_Boolean => "bool",
                        SpecialType.System_Double or SpecialType.System_Single => "double",
                        SpecialType.System_Int32 or SpecialType.System_Int64 or SpecialType.System_Int16 or SpecialType.System_Byte or SpecialType.System_UInt32 => "int",
                        _ => property.Type.TypeKind == TypeKind.Enum ? "enum" : referenceType switch {
                            "Sunfleck.Command" => "command", "Sunfleck.PropertyModel" => "model", "Sunfleck.Color" => "color",
                            "Sunfleck.Thickness" => "thickness", "Sunfleck.CornerRadius" => "cornerRadius", "Sunfleck.Point" => "point",
                            "Sunfleck.Size" => "size", "Sunfleck.Matrix" => "matrix", "Sunfleck.Length" => "length", _ => ""
                        }
                    };
                    if (propertyKind.Length == 0) { Error("Unsupported Fleck property type: " + property.Type.ToDisplayString() + ". Use PropertyModel for model references."); continue; }
                    if (mode is < 0 or > 3) { Error("Invalid default binding mode for " + property.Name); continue; }
                    if (defaultValue.Value is { } declaredDefault) {
                        bool valid = propertyKind switch {
                            "string" or "color" or "thickness" or "cornerRadius" or "point" or "size" or "matrix" or "length" => declaredDefault is string,
                            "bool" => declaredDefault is bool,
                            "int" or "enum" => declaredDefault is byte or sbyte or short or ushort or int or uint or long,
                            "double" => declaredDefault is byte or sbyte or short or ushort or int or uint or long or float or double && double.IsFinite(Convert.ToDouble(declaredDefault)),
                            _ => false
                        };
                        if (!valid) { Error("Default value does not match Fleck property " + property.Name + " (" + propertyKind + ")."); continue; }
                    }
                    if (propertyKind is "color" or "thickness" or "cornerRadius" or "point" or "size" or "matrix" or "length" or "enum") {
                        literal = defaultValue.Value is null ? "default(" + property.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) + ")" :
                            defaultValue.Value is string ? "global::Sunfleck.PropertyValues.Parse<" + property.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) + ">(" + literal + ")" :
                            "(" + property.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) + ")" + literal;
                    }
                    if (!readOnly && property.SetMethod?.DeclaredAccessibility != Accessibility.Public) { Error("Fleck property " + property.Name + " requires a public setter or ReadOnly=true."); continue; }
                    if (readOnly && mode == 2) { Error("Read-only Fleck property " + property.Name + " cannot default to TwoWay binding."); continue; }
                    bool canAnimate = propertyKind is "int" or "double" or "color" or "thickness" or "cornerRadius" or "point" or "size" or "matrix" or "length";
                    if (effects != -1 && (effects < 0 || (effects & ~255) != 0 ||
                        ((effects & 2) != 0 && (readOnly || (effects & 1) == 0)) ||
                        ((effects & 64) != 0 && !canAnimate) || (mode == 2 && (effects & 2) == 0))) {
                        Error("Invalid property effects for " + property.Name); continue;
                    }
                    var metadataEntry = new Dictionary<string, object?> { ["name"] = property.Name, ["type"] = propertyKind, ["mode"] = mode == 2 ? "TwoWay" : mode == 1 ? "OneTime" : "OneWay", ["readOnly"] = readOnly ? 1 : 0 };
                    if (effects != -1) { metadataEntry["flags"] = effects; }
                    var propertyLocation = property.Locations.FirstOrDefault(l => l.IsInSource)?.GetLineSpan();
                    if (propertyLocation is { } position) { metadataEntry["source"] = new { uri = position.Path, line = position.StartLinePosition.Line + 1, column = position.StartLinePosition.Character + 1 }; }
                    if (defaultValue.Value is { } initial) { metadataEntry["default"] = propertyKind is "double" or "enum" ? Convert.ToString(initial, System.Globalization.CultureInfo.InvariantCulture) : initial is bool boolean ? (object)(boolean ? 1 : 0) : initial; }
                    propertyMetadata.Add(metadataEntry);
                    code.Append("new(").Append(Quote(property.Name)).Append(",typeof(").Append(property.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)).Append("),").Append(literal).Append(',').Append(readOnly ? "true" : "false").Append(",(global::Sunfleck.PropertyBindingMode)").Append(mode).Append(',').Append(effects == -1 ? "null" : "(global::Sunfleck.PropertyEffects)" + effects).Append("),\n");
                }
                code.Append("}, templateNamespace: ").Append(Quote(Named("TemplateNamespace"))).Append(", template: ").Append(Quote(Named("Template"))).Append(", events: new string[] {");
                foreach (var eventName in eventMetadata) { code.Append(Quote(eventName)).Append(','); }
                code.Append("}, parts: new global::Sunfleck.TemplatePart[] {");
                foreach (var part in partMetadata) { code.Append("new(").Append(Quote((string)part["name"]!)).Append(",global::Sunfleck.NodeKind.").Append(part["kind"]).Append(',').Append((int)part["required"]! == 1 ? "true" : "false").Append("),"); }
                code.Append("});\n");
            }
        }
        code.Append("} }\n");
        if (context.Compilation.Options.OutputKind is OutputKind.ConsoleApplication or OutputKind.WindowsApplication) {
            code.Append("public static class FleckComponentExtensions { public static void RegisterFleckComponents(this global::Sunfleck.App app) => ").Append(registry).Append(".Register(app); }\n");
        }
        code.Append("}\n");
        var manifest = JsonSerializer.Serialize(new { version = 1, types = manifestTypes, definitions });
        var generated = code.ToString().Replace("namespace Sunfleck.Generated {", "[assembly: global::Sunfleck.FleckManifestAttribute(" + Quote(manifest) + ")]\nnamespace Sunfleck.Generated {");
        context.AddSource("FleckComponents.g.cs", generated);
    }
}
