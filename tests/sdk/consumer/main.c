#include <sunfleck/ui.h>
#include <string.h>
int main(void)
{
    const ui_app_options options = {sizeof(options), UI_API_VERSION, UI_SOFTWARE, UI_HEADLESS};
    ui_app* app = NULL;
    if (ui_app_create(&options, &app) != UI_OK) return 1;
    const char* xml = "<Window xmlns='urn:sunfleck:v1'><TextBlock Id='hello' TabIndex='7' Text='Installed C SDK'/></Window>";
    ui_result result = ui_app_load_fleck(app, xml, strlen(xml), NULL);
    ui_model* rows = NULL;
    const char* labels[] = {"first", "second"};
    const char* label = NULL;
    uint64_t item_id = 0;
    if (result == UI_OK) result = ui_model_create(app, &rows);
    if (result == UI_OK) result = ui_model_enable_text_collection(rows);
    if (result == UI_OK) result = ui_collection_splice(rows, 0, 0, labels, 2);
    if (result == UI_OK) result = ui_collection_move(rows, 1, 1, 0);
    if (result == UI_OK) result = ui_collection_item(rows, 0, &item_id, &label);
    if (result == UI_OK && (!item_id || strcmp(label, "second"))) result = UI_ERROR_INVALID_STATE;
    ui_model* grouped = NULL;
    uint32_t group_count = 0;
    if (result == UI_OK) result = ui_model_create(app, &grouped);
    if (result == UI_OK) result = ui_collection_set_view(grouped, rows, UI_COLLECTION_SOURCE_ORDER, "");
    if (result == UI_OK) result = ui_collection_set_group_by_label(grouped, 1);
    if (result == UI_OK) result = ui_collection_group_count(grouped, &group_count);
    if (result == UI_OK && group_count != 2) result = UI_ERROR_INVALID_STATE;
    if (grouped) ui_model_destroy(grouped);
    if (rows) ui_model_destroy(rows);
    ui_node* node = NULL;
    if (result == UI_OK) result = ui_app_find_fleck_node(app, "hello", &node);
    if (result == UI_OK) result = ui_node_set_key_binding(node, UI_KEY_F8, 0, UI_EVENT_PREVIEW, "IncrementCount");
    if (result == UI_OK) result = ui_node_set_key_binding(node, UI_KEY_F8, 0, UI_EVENT_PREVIEW, NULL);
    ui_binding_value tab = {0};
    if (result == UI_OK) result = ui_node_get_property(node, UI_PROPERTY_TAB_INDEX, &tab);
    if (result == UI_OK && (tab.kind != UI_VALUE_INT || tab.integer != 7)) result = UI_ERROR_INVALID_STATE;
    ui_binding_value resource_opacity = {0}; resource_opacity.kind = UI_VALUE_DOUBLE; resource_opacity.number = .75;
    if (result == UI_OK) result = ui_app_set_theme_resource(app, "Fade", &resource_opacity);
    if (result == UI_OK) result = ui_node_set_resource_reference(node, UI_PROPERTY_OPACITY, UI_PRECEDENCE_STYLE, "Fade");
    if (result == UI_OK) result = ui_node_get_property(node, UI_PROPERTY_OPACITY, &resource_opacity);
    if (result == UI_OK && resource_opacity.number != .75) result = UI_ERROR_INVALID_STATE;
    if (result == UI_OK) result = ui_app_set_theme_resource(app, "Fade", NULL);
    ui_binding_value font_size = {0}; font_size.kind = UI_VALUE_DOUBLE; font_size.number = 23.5;
    if (result == UI_OK) result = ui_node_set_property(node, UI_PROPERTY_FONT_SIZE, &font_size);
    if (result == UI_OK) result = ui_node_get_property(node, UI_PROPERTY_FONT_SIZE, &font_size);
    if (result == UI_OK && font_size.number != 23.5) result = UI_ERROR_INVALID_STATE;
    ui_binding_value flow = {0}; flow.kind = UI_VALUE_ENUM; flow.integer = UI_FLOW_RIGHT_TO_LEFT;
    if (result == UI_OK) result = ui_node_set_property(node, UI_PROPERTY_FLOW_DIRECTION, &flow);
    if (result == UI_OK) result = ui_node_get_property(node, UI_PROPERTY_FLOW_DIRECTION, &flow);
    if (result == UI_OK && flow.integer != UI_FLOW_RIGHT_TO_LEFT) result = UI_ERROR_INVALID_STATE;
    ui_binding_value ink = {0}; ink.kind = UI_VALUE_COLOR; ink.integer = 0x80224466;
    if (result == UI_OK) result = ui_node_set_property(node, UI_PROPERTY_FOREGROUND, &ink);
    if (result == UI_OK) result = ui_node_get_property(node, UI_PROPERTY_FOREGROUND, &ink);
    if (result == UI_OK && ink.integer != 0x80224466) result = UI_ERROR_INVALID_STATE;
    ui_binding_value width = {0}; width.kind = UI_VALUE_INT; width.integer = 120;
    if (result == UI_OK) result = ui_node_set_property(node, UI_PROPERTY_WIDTH, &width);
    ui_property_id registered_width = 0;
    if (result == UI_OK) result = ui_node_resolve_property(node, "Width", &registered_width);
    ui_registered_property_descriptor registered = {0}; registered.struct_size = sizeof(registered); registered.version = 1;
    if (result == UI_OK) result = ui_node_describe_registered_property(node, registered_width, &registered);
    if (result == UI_OK && (registered.kind != UI_VALUE_LENGTH || registered.id != registered_width)) result = UI_ERROR_INVALID_STATE;
    ui_binding_value registered_value = {0};
    if (result == UI_OK) result = ui_node_get_registered_property(node, registered_width, &registered_value);
    if (result == UI_OK && (registered_value.kind != UI_VALUE_LENGTH || registered_value.integer != UI_LENGTH_PIXELS || registered_value.number != 120)) result = UI_ERROR_INVALID_STATE;
    ui_property_source source = UI_PROPERTY_SOURCE_DEFAULT;
    if (result == UI_OK) result = ui_node_get_property_source(node, UI_PROPERTY_WIDTH, &source);
    if (result == UI_OK && source != UI_PROPERTY_SOURCE_LOCAL) result = UI_ERROR_INVALID_STATE;
    if (result == UI_OK) result = ui_node_clear_property(node, UI_PROPERTY_WIDTH);
    if (result == UI_OK) result = ui_node_set_property_layer(node, UI_PROPERTY_WIDTH, UI_PRECEDENCE_STYLE, &width);
    ui_binding_value parsed = {0}; double geometry[2] = {0};
    if (result == UI_OK) result = ui_value_parse(UI_VALUE_POINT, "1.25,2.5", &parsed, geometry, 2);
    if (result == UI_OK && (geometry[0] != 1.25 || geometry[1] != 2.5)) result = UI_ERROR_INVALID_STATE;
    ui_model* context = NULL;
    if (result == UI_OK) result = ui_model_create(app, &context);
    if (result == UI_OK) result = ui_node_set_data_context(node, context);
    ui_model* effective = NULL;
    if (result == UI_OK) result = ui_node_get_data_context(node, &effective);
    if (result == UI_OK && effective != context) result = UI_ERROR_INVALID_STATE;
    ui_binding_value context_value = {0};
    if (result == UI_OK) result = ui_node_get_property(node, UI_PROPERTY_DATA_CONTEXT, &context_value);
    if (result == UI_OK && (context_value.kind != UI_VALUE_MODEL || context_value.model != context)) result = UI_ERROR_INVALID_STATE;
    ui_property_descriptor context_descriptor = {0}; context_descriptor.struct_size = sizeof(context_descriptor); context_descriptor.version = 1;
    if (result == UI_OK) result = ui_property_describe(UI_TEXT_BLOCK, UI_PROPERTY_DATA_CONTEXT, &context_descriptor);
    if (result == UI_OK && !(context_descriptor.flags & UI_PROPERTY_INHERITS)) result = UI_ERROR_INVALID_STATE;
    if (result == UI_OK) result = ui_node_clear_data_context(node);
    if (result == UI_OK) result = ui_model_destroy(context);
    width.integer = 2;
    if (result == UI_OK) result = ui_node_set_property(node, UI_PROPERTY_WEIGHT, &width);
    if (result == UI_OK) result = ui_node_get_property(node, UI_PROPERTY_WEIGHT, &width);
    if (result == UI_OK && width.integer != 2) result = UI_ERROR_INVALID_STATE;
    ui_node* metrics = NULL;
    if (result == UI_OK) result = ui_node_create(app, UI_STACK_PANEL, &metrics);
    if (result == UI_OK) result = ui_node_set_layout(metrics, 1.25, 2.75);
    ui_binding_value metric = {0};
    if (result == UI_OK) result = ui_node_get_property(metrics, UI_PROPERTY_PADDING, &metric);
    if (result == UI_OK && (metric.kind != UI_VALUE_DOUBLE || metric.number != 2.75)) result = UI_ERROR_INVALID_STATE;
    ui_node* path = NULL;
    ui_brush_desc fill = {0};
    fill.kind = UI_BRUSH_SOLID;
    fill.color.argb = 0xff12ab34;
    if (result == UI_OK) result = ui_node_create(app, UI_PATH, &path);
    if (result == UI_OK) result = ui_path_set_data(path, "M0,0 L10,0 L0,10 Z");
    if (result == UI_OK) result = ui_node_set_brush(path, UI_BRUSH_BACKGROUND, &fill);
    if (result == UI_OK) result = ui_app_open_window(app);
    if (result == UI_OK) result = ui_node_register_visual_state(node,"Input","Normal",NULL);
    if (result == UI_OK) result = ui_node_go_to_visual_state(node,"Input","Normal");
    ui_key_frame frames[2] = {0};
    frames[0].value.kind = frames[1].value.kind = UI_VALUE_DOUBLE;
    frames[1].position = frames[1].value.number = 1;
    const ui_timeline fade = {frames,2,200,0,1,0,0};
    if (result == UI_OK) result = ui_app_advance_animation_clock(app,0);
    if (result == UI_OK) result = ui_node_start_animation(node,UI_PROPERTY_OPACITY,&fade);
    if (result == UI_OK) result = ui_app_advance_animation_clock(app,100);
    if (result == UI_OK) result = ui_app_poll(app, 0);
    ui_binding_value opacity = {0};
    if (result == UI_OK) result = ui_node_get_property(node,UI_PROPERTY_OPACITY,&opacity);
    if (result == UI_OK && opacity.number != .5) result = UI_ERROR_INVALID_STATE;
    ui_app_destroy(app);
    return result == UI_OK ? 0 : 2;
}
